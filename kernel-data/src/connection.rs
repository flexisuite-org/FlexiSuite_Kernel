pub struct RawConnection {
    pub(crate) txn: DatabaseTransaction,
}

impl RawConnection {
    pub(crate) fn new(txn: DatabaseTransaction) -> Self {
        Self { txn }
    }
}

/// A wrapper around a database transaction that is guaranteed to be scoped to a specific tenant.
pub struct TenantScoped<C> {
    pub(crate) inner: C,
    pub(crate) tenant_id: crate::auth_context::TenantId,
    pub(crate) user_id: Option<crate::auth_context::UserId>,
}

impl<C> TenantScoped<C> {
    pub(super) fn new(
        inner: C,
        tenant_id: crate::auth_context::TenantId,
        user_id: Option<crate::auth_context::UserId>,
    ) -> Self {
        Self {
            inner,
            tenant_id,
            user_id,
        }
    }
}

impl TenantScoped<RawConnection> {
    #[cfg(not(feature = "test-utils"))]
    pub(crate) fn txn(&self) -> &DatabaseTransaction {
        &self.inner.txn
    }

    /// # Safety
    ///
    /// This method exposes the raw database transaction, bypassing strict tenant scoping.
    /// Callers MUST ensure that any operations performed using this transaction
    /// are authorized via `flexi.authorize_tenant` or otherwise maintain tenant isolation invariants.
    ///
    /// This is exposed primarily for test seeding and special integration scenarios.
    #[cfg(feature = "test-utils")]
    pub fn txn(&self) -> &DatabaseTransaction {
        &self.inner.txn
    }

    pub(crate) async fn commit(self) -> Result<(), DbErr> {
        self.inner.txn.commit().await
    }

    pub(crate) async fn rollback(self) -> Result<(), DbErr> {
        self.inner.txn.rollback().await
    }
}

