/// Executes a closure within a tenant-scoped transaction.
///
/// **Note:** This function relies on the `flexi.authorize_tenant` PL/pgSQL function.
/// The `token` must be a valid signed v2 token generated by `KeyManager`.
pub async fn with_tenant_tx<F, R>(
    pool: &DatabaseConnection,
    ctx: &TenantContext,
    token: &str,
    f: F,
) -> Result<R, DataError>
where
    F: for<'c> FnOnce(&'c TenantScoped<RawConnection>) -> BoxFuture<'c, Result<R, DataError>>
        + Send,
    R: Send,
{
    let txn = pool.begin().await.map_err(DataError::DbError)?;

    // 1. Authorize
    if let Err(e) = txn
        .execute(Statement::from_sql_and_values(
            DbBackend::Postgres,
            "SELECT flexi.authorize_tenant($1)",
            [token.into()],
        ))
        .await
    {
        // Log a sanitized message only; do not interpolate the raw DB error
        // to avoid leaking token KID or other sensitive fields into log sinks.
        warn!("Tenant authorization failed");

        let error_msg = e.to_string();
        let safe_error = [
            "Nonce already used",
            "Internal HMAC secret not set",
            "Invalid signature",
            "Token timestamp expired or future (skew > 30s)",
            "Missing or empty tenant token",
            "Invalid token format",
            crate::error::INVALID_OR_EXPIRED_KEY_ID,
        ]
        .iter()
        .find(|&&m| error_msg.contains(m))
        .map(|&m| m.to_string())
        .unwrap_or_else(|| "tenant authorization failed".to_string());

        if let Err(rollback_err) = txn.rollback().await {
            error!("rollback failed after authorization failure: {rollback_err}");
        }
        return Err(DataError::TenantAuthorizationFailed(safe_error));
    }

    let token_tenant = if let Some(tid) = parse_tenant_from_token(token) {
        tid
    } else {
        if let Err(rollback_err) = txn.rollback().await {
            error!("rollback failed after token parse failure: {rollback_err}");
        }
        return Err(DataError::TenantAuthorizationFailed(
            "invalid tenant token format".to_string(),
        ));
    };
    if token_tenant != ctx.tenant_id().as_str() {
        warn!(
            expected_tenant = %ctx.tenant_id(),
            token_tenant = %token_tenant,
            "tenant mismatch between context and token"
        );
        if let Err(rollback_err) = txn.rollback().await {
            error!("rollback failed after tenant mismatch: {rollback_err}");
        }
        return Err(DataError::TenantAuthorizationFailed(
            "tenant mismatch between context and token".to_string(),
        ));
    }

    let scoped = TenantScoped::new(
        RawConnection::new(txn),
        ctx.tenant_id().clone(),
        ctx.user_id().cloned(),
    );

    match f(&scoped).await {
        Ok(result) => match scoped.commit().await {
            Ok(()) => Ok(result),
            Err(commit_err) => {
                error!(
                    tenant_id = %ctx.tenant_id(),
                    "commit failed (outcome unknown): {commit_err}"
                );
                Err(DataError::CommitUnknown(commit_err.to_string()))
            }
        },
        Err(e) => {
            if let Err(rollback_err) = scoped.rollback().await {
                error!("rollback failed: {rollback_err}");
            }
            warn!(tenant_id = %ctx.tenant_id(), "tx rolled back: {e}");
            Err(e)
        }
    }
}

fn parse_tenant_from_token(token: &str) -> Option<&str> {
    let mut parts = token.split(':');
    let ver = parts.next()?;
    let _kid = parts.next()?;
    let _ts = parts.next()?;
    let _nonce = parts.next()?;
    let tenant_id = parts.next()?;
    let _sig = parts.next()?;
    if ver != "v2" || parts.next().is_some() {
        return None;
    }
    Some(tenant_id)
}

